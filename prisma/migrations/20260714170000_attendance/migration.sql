-- Hand-edited (Task 7): Prisma's schema DSL has no way to express a PARTIAL
-- unique index (`CREATE UNIQUE INDEX ... WHERE ...`) — `@@unique` always
-- covers the whole table. The real constraint we need is "at most one
-- *active* (status <> 'cancelled') Attendance row per (matchId, playerId)"
-- — a cancelled row must NOT block a fresh confirm from the same player on
-- the same match. So the index below is written by hand, not generated by
-- `prisma migrate diff`, and there's no corresponding `@@unique` in
-- schema.prisma for it (see the `Attendance` model's doc comment). Re-running
-- `prisma migrate diff` against the current schema does not reintroduce this
-- statement (verified below) — a partial index the schema DSL can't model is
-- invisible to the diff, not drift.
CREATE UNIQUE INDEX "attendance_active_unique" ON "Attendance" ("matchId", "playerId") WHERE status <> 'cancelled';

